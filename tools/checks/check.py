"""Repository checks that clippy cannot reach (rule 17)."""

# السكربتُ الواحد لما لا يبلغه clippy (القاعدة ١٧).
# الأوامر:
#   clippy-config          يولّد clippy.toml في الجذر ولكلّ حزمة من clippy_policy.toml
#   clippy-config --check  يفشل إن خالف ملفٌّ مولَّدٌ مصدرَه (للتكامل المستمرّ)
#   crate-deps             يفحص اتّجاهَ التبعيّة، ويولّد جدولَ crates/dependencies.md
#   crate-deps --check     يفحص، ويفشل إن تقادم الجدول (للتكامل المستمرّ)
#   ويرفض crate-deps كلَّ صندوقٍ خارجيّ: كلُّ تبعيّةٍ مسارٌ في crates/، ولا مصدرَ في Cargo.lock
#   (ق‑٥، قرارُ المالك ٢٠٢٦-١١-٢٧: «لا صناديق خارجية واداة نكتبها»).

import argparse
import json
import sys
import tomllib
from pathlib import Path

# أدواتُ الفحص وسياساتُه من مجلّد السكربت نفسِه، والشجرةُ المفحوصة من --root.
# فتشغّل البوّابةُ سكربتَ الفرع الأساسيّ وسياساتِه على شجرة الطلب (القاعدة ٨١).
TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parents[1]
POLICY = TOOLS / "clippy_policy.toml"
CRATES = ROOT / "crates"
KEYS = ("disallowed-macros", "disallowed-methods", "disallowed-types")
HEADER = (
    "# Generated by tools/checks/check.py from tools/checks/clippy_policy.toml.\n"
    "# Do not edit: change the policy and run `python tools/checks/check.py clippy-config`.\n"
)


def fail(message: str) -> None:
    print(f"check.py: {message}", file=sys.stderr)
    sys.exit(1)


def load_policy() -> dict:
    with POLICY.open("rb") as f:
        return tomllib.load(f)


def entry(path: str, reason: str) -> dict:
    return {"path": path, "reason": reason}


def base_entries(policy: dict) -> dict[str, list[dict]]:
    base = policy.get("base", {})
    out = {key: list(base.get(key, [])) for key in KEYS}
    floats = base.get("float-functions", {})
    for ty in floats.get("types", []):
        for name in floats.get("transcendental", []):
            out["disallowed-methods"].append(entry(f"{ty}::{name}", floats["transcendental-reason"]))
        for name in floats.get("fused", []):
            out["disallowed-methods"].append(entry(f"{ty}::{name}", floats["fused-reason"]))
    return out


def crate_names() -> list[str]:
    return sorted(p.name for p in CRATES.iterdir() if (p / "Cargo.toml").is_file())


def validate(policy: dict, crates: list[str]) -> None:
    known = set(crates)
    for group in policy.get("group", []):
        if not isinstance(group.get("rule"), int):
            fail(f"group without integer 'rule': {group}")
        for name in group.get("crates", []):
            if name not in known:
                fail(f"rule {group['rule']}: unknown crate '{name}'")
        for key in group:
            if key not in ("rule", "crates", *KEYS):
                fail(f"rule {group['rule']}: unknown key '{key}'")
    for key in policy.get("base", {}):
        if key not in (*KEYS, "float-functions"):
            fail(f"base: unknown key '{key}'")


def render(entries: dict[str, list[dict]]) -> str:
    lines = [HEADER]
    for key in KEYS:
        items = entries[key]
        if not items:
            continue
        seen = set()
        lines.append(f"{key} = [")
        for item in items:
            if item["path"] in seen:
                fail(f"duplicate path '{item['path']}' in {key}")
            seen.add(item["path"])
            path = json.dumps(item["path"])
            reason = json.dumps(item["reason"])
            lines.append(f"    {{ path = {path}, reason = {reason} }},")
        lines.append("]")
    return "\n".join(lines) + "\n"


def planned_files(policy: dict) -> dict[Path, str]:
    crates = crate_names()
    validate(policy, crates)
    base = base_entries(policy)
    files = {ROOT / "clippy.toml": render(base)}
    for name in crates:
        entries = {key: list(values) for key, values in base.items()}
        for group in policy.get("group", []):
            if name in group.get("crates", []):
                for key in KEYS:
                    entries[key].extend(group.get(key, []))
        files[CRATES / name / "clippy.toml"] = render(entries)
    return files


def clippy_config(check: bool) -> None:
    stale = []
    for path, text in planned_files(load_policy()).items():
        # تُقارن البايتات، فـread_text يحوّل CRLF إلى LF ويخفيه (القاعدة ٣٣).
        current = path.read_bytes() if path.is_file() else None
        if current == text.encode("utf-8"):
            continue
        if check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        fail("rule 22: generated clippy.toml out of date: " + ", ".join(stale))


DEPS = TOOLS / "crate_deps.toml"
DEPS_DOC = CRATES / "dependencies.md"
DOC_BEGIN = "<!-- generated:crate-deps:begin -->"
DOC_END = "<!-- generated:crate-deps:end -->"
DEP_TABLES = ("dependencies", "dev-dependencies", "build-dependencies")


def load_deps_policy() -> dict:
    with DEPS.open("rb") as f:
        return tomllib.load(f)


def validate_deps_policy(policy: dict) -> dict[str, dict]:
    crates = policy.get("crates", {})
    layers = policy.get("layers", {})
    on_disk = set(crate_names())
    listed = set(crates)
    for name in sorted(on_disk - listed):
        fail(f"rule 25: crate '{name}' missing from crate_deps.toml")
    for name in sorted(listed - on_disk):
        fail(f"rule 25: crate_deps.toml lists unknown crate '{name}'")
    for name, spec in crates.items():
        layer = spec.get("layer")
        if not isinstance(layer, int) or str(layer) not in layers:
            fail(f"rule 25: '{name}' has undeclared layer {layer!r}")
        for dep in spec.get("deps", []):
            if dep not in crates:
                fail(f"rule 25: '{name}' allows unknown crate '{dep}'")
            if crates[dep]["layer"] >= layer:
                fail(f"rule 25: '{name}' (layer {layer}) -> '{dep}' (layer {crates[dep]['layer']}) is not downward")
    # من لا يحقّ له بلوغُ حزمة LLVM لا يبلغها ولو بواسطة
    llvm = policy["llvm-crate"]
    users = set(policy.get("llvm-users", []))
    for name in crates:
        if name == llvm or name in users:
            continue
        if llvm in reachable(name, crates):
            fail(f"rule 25: '{name}' reaches '{llvm}' but is not in llvm-users")
    return crates


def reachable(start: str, crates: dict[str, dict]) -> set[str]:
    seen: set[str] = set()
    stack = list(crates[start].get("deps", []))
    while stack:
        dep = stack.pop()
        if dep not in seen:
            seen.add(dep)
            stack.extend(crates[dep].get("deps", []))
    return seen


def declared_internal_deps(manifest: dict) -> set[str]:
    tables = [manifest]
    tables.extend(manifest.get("target", {}).values())
    found: set[str] = set()
    for table in tables:
        for kind in DEP_TABLES:
            for key, value in table.get(kind, {}).items():
                real = value.get("package", key) if isinstance(value, dict) else key
                is_path = isinstance(value, dict) and "path" in value
                if real.startswith("sad_") or is_path:
                    found.add(real)
    return found


def external_deps(name: str, manifest: dict) -> list[str]:
    # التبعيّةُ الداخليّة مسارٌ يقع تحت crates/ نفسِه، لا أيُّ مسار (مراجعةُ أميليا الثانية، ث‑٦).
    tables = [manifest]
    tables.extend(manifest.get("target", {}).values())
    found = []
    for table in tables:
        for kind in DEP_TABLES:
            for key, value in table.get(kind, {}).items():
                if not (isinstance(value, dict) and "path" in value):
                    found.append(f"{key} ({kind})")
                    continue
                target = (CRATES / name / value["path"]).resolve()
                if target.parent != CRATES.resolve():
                    found.append(f"{key} ({kind}) at path outside crates/: {value['path']}")
    return sorted(found)


def check_lints(crates: dict[str, dict], llvm: str) -> list[str]:
    # القاعدة ٣: كلُّ صندوقٍ يرث [workspace.lints]، وفيه unsafe_code = "forbid".
    # إلّا صندوقَ الوصل بـLLVM: جدولُه نسخةٌ منه بلا unsafe_code، ولا يزيد عليه ولا ينقص.
    with (ROOT / "Cargo.toml").open("rb") as f:
        workspace = tomllib.load(f)["workspace"].get("lints", {})
    errors = []
    if workspace.get("rust", {}).get("unsafe_code") != "forbid":
        errors.append('[workspace.lints.rust] must set unsafe_code = "forbid"')
    expected = {
        "rust": {k: v for k, v in workspace.get("rust", {}).items() if k != "unsafe_code"},
        "clippy": workspace.get("clippy", {}),
    }
    for name in sorted(crates):
        with (CRATES / name / "Cargo.toml").open("rb") as f:
            lints = tomllib.load(f).get("lints", {})
        if name == llvm:
            if lints != expected:
                errors.append(f"'{name}' [lints] must equal [workspace.lints] without unsafe_code")
        elif lints != {"workspace": True}:
            errors.append(f"'{name}' must use [lints] workspace = true")
    return errors


def lock_external() -> list[str]:
    found = []
    with (ROOT / "Cargo.toml").open("rb") as f:
        workspace = tomllib.load(f)
    for key in workspace.get("workspace", {}).get("dependencies", {}):
        found.append(f"workspace.dependencies has '{key}'")
    with (ROOT / "Cargo.lock").open("rb") as f:
        lock = tomllib.load(f)
    for package in lock.get("package", []):
        if "source" in package:
            found.append(f"Cargo.lock has '{package['name']}' from {package['source']}")
    return found


def check_manifests(crates: dict[str, dict]) -> None:
    errors = []
    external = lock_external()
    for name, spec in sorted(crates.items()):
        with (CRATES / name / "Cargo.toml").open("rb") as f:
            manifest = tomllib.load(f)
        for dep in external_deps(name, manifest):
            external.append(f"'{name}' depends on external crate {dep}")
        allowed = set(spec.get("deps", []))
        for dep in sorted(declared_internal_deps(manifest) - allowed):
            errors.append(f"'{name}' depends on '{dep}', not allowed by crate_deps.toml")
    # لا صناديقَ خارجيّة: كلُّ تبعيّةٍ مسارٌ في crates/، ولا مصدرَ في Cargo.lock (ق‑٥).
    if external:
        fail("Q-5: no external crates:\n  " + "\n  ".join(external))
    lint_errors = check_lints(crates, load_deps_policy()["llvm-crate"])
    if lint_errors:
        fail("rule 3:\n  " + "\n  ".join(lint_errors))
    if errors:
        fail("rule 25:\n  " + "\n  ".join(errors))


def render_deps_table(policy: dict, crates: dict[str, dict]) -> str:
    doc = policy["doc"]
    rows = [doc["table-header"]]
    ordered = sorted(crates.items(), key=lambda item: (item[1]["layer"], item[0]))
    for name, spec in ordered:
        layer = spec["layer"]
        layer_name = policy["layers"][str(layer)]
        deps = ", ".join(f"`{d}`" for d in spec.get("deps", [])) or doc["none"]
        rows.append(f"| {layer} {layer_name} | `{name}` | {deps} |")
    return "\n".join(rows)


def crate_deps(check: bool) -> None:
    policy = load_deps_policy()
    crates = validate_deps_policy(policy)
    check_manifests(crates)
    raw = DEPS_DOC.read_bytes()
    text = raw.decode("utf-8")
    if DOC_BEGIN not in text or DOC_END not in text:
        fail(f"{DEPS_DOC.relative_to(ROOT).as_posix()}: generated markers missing")
    head, rest = text.split(DOC_BEGIN, 1)
    _, tail = rest.split(DOC_END, 1)
    table = render_deps_table(policy, crates)
    updated = f"{head}{DOC_BEGIN}\n{table}\n{DOC_END}{tail}"
    if updated.encode("utf-8") == raw:
        return
    if check:
        fail("rule 22: crates/dependencies.md table out of date")
    DEPS_DOC.write_text(updated, encoding="utf-8", newline="\n")


def error_pages(site: Path) -> None:
    # ق‑٦ (ب)٣: لكلّ خطأٍ في data/errors/ صفحتُه في الموقع، عنوانُها رمزُه واسمُه، وفيها سطرُه.
    # ولا صفحةَ خطأٍ في الموقع بلا خطأٍ في الفهرس.
    docs = site / "src" / "content" / "docs"
    errors = []
    pages = set()
    for path in sorted((ROOT / "data" / "errors").glob("*.toml")):
        if path.name == "catalog.toml":
            continue
        with path.open("rb") as f:
            family = tomllib.load(f)
        for e in family.get("error", []):
            code, name, page = e["code"], e["name"], e["page"]
            file = docs / f"{page}.mdx"
            pages.add(file.resolve())
            if not file.is_file():
                errors.append(f"{code}: page {page}.mdx is missing")
                continue
            text = file.read_text(encoding="utf-8")
            if f'title: "{code} {name}"' not in text:
                errors.append(f"{code}: {page}.mdx title is not \"{code} {name}\"")
            if f"[{code} {name}]" not in text:
                errors.append(f"{code}: {page}.mdx never shows [{code} {name}]")
    # كلُّ صفحةٍ تحت مجلّدات العائلات، بأيّ عمقٍ وبالامتدادين، وفهرسُ الأخطاء في الجذر مستثنًى.
    errors_dir = docs / "reference" / "errors"
    found = [f for ext in ("*.md", "*.mdx") for f in errors_dir.rglob(ext) if f.parent != errors_dir]
    for file in sorted(found):
        if file.resolve() not in pages:
            errors.append(f"{file.relative_to(docs).as_posix()}: page has no error in data/errors/")
    if errors:
        fail("Q-6 (b)3: error pages:\n  " + "\n  ".join(errors))


def main() -> None:
    global ROOT, CRATES, DEPS_DOC, POLICY, DEPS
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, help="tree to check (default: this script's repo)")
    # سياساتُ الطلب نفسِه: فالصندوقُ الجديد وسياستُه في طلبٍ واحد، وتغييرُ السياسة لا يمرّ إلّا بموافقة المالك
    # (CODEOWNERS، القاعدة ٢٠). أمّا شفرةُ الفحص فمن الفرع الأساسيّ، فلا يُضعفها الطلب (القاعدة ٨١).
    parser.add_argument("--policies", type=Path, help="folder of clippy_policy.toml and crate_deps.toml")
    sub = parser.add_subparsers(dest="command", required=True)
    cfg = sub.add_parser("clippy-config", help="generate clippy.toml files from the policy")
    cfg.add_argument("--check", action="store_true", help="fail if generated files are stale")
    deps = sub.add_parser("crate-deps", help="check crate dependency direction (rule 25)")
    deps.add_argument("--check", action="store_true", help="fail if the doc table is stale")
    pages = sub.add_parser("error-pages", help="check that every error has its site page")
    pages.add_argument("--site", type=Path, required=True, help="the site folder of the rules repo")
    args = parser.parse_args()
    if args.root:
        ROOT = args.root.resolve()
        CRATES = ROOT / "crates"
        DEPS_DOC = CRATES / "dependencies.md"
    if args.policies:
        POLICY = args.policies.resolve() / "clippy_policy.toml"
        DEPS = args.policies.resolve() / "crate_deps.toml"
    if args.command == "error-pages":
        error_pages(args.site)
    elif args.command == "clippy-config":
        clippy_config(args.check)
    elif args.command == "crate-deps":
        crate_deps(args.check)


if __name__ == "__main__":
    main()
